let fault;
export function setLabTransactionFault(callback) {
  if (process.env.NODE_ENV !== "test") throw new Error("Transaction fault injection is only available in tests");
  fault = callback;
}
export const generateAccessionBarcode = (orderId, sequence = 1) => {
  requireRecordId(orderId, "laboratory order");
  if (!Number.isSafeInteger(sequence) || sequence < 1 || sequence > 50) throw accessError(400, "Invalid sample sequence");
  return `LAB-${String(orderId).toUpperCase()}-${sequence}`;
};
const fingerprint = data => crypto.createHash("sha256").update(JSON.stringify(data)).digest("hex");
async function transaction(callback) {
  if (mongoose.connection.readyState !== 1) throw accessError(503, "Database service is unavailable");
  const session = await mongoose.startSession();
  try { return await session.withTransaction(() => callback(session), { readConcern: { level: "snapshot" }, writeConcern: { w: "majority" }, maxCommitTimeMS: 10000 }); }
  catch (error) { if ([20, 303].includes(error.code)) throw accessError(503, "Laboratory operations require a transaction-capable database"); throw error; }
  finally { await session.endSession(); }
}
function command(input, kind) {
  if (!input.requestKey || input.expectedRevision === undefined) throw accessError(428, "Idempotency-Key and the current workflow revision are required");
  if (typeof input.requestKey !== "string" || !/^[A-Za-z0-9._:-]{8,128}$/.test(input.requestKey)) throw accessError(400, "Invalid Idempotency-Key");
  if (!Number.isSafeInteger(input.expectedRevision) || input.expectedRevision < 0) throw accessError(400, "Invalid workflow revision");
  let results;
  if (["results", "correct"].includes(kind)) {
    const rows = kind === "correct" ? input.newResults : input.results;
    if (!Array.isArray(rows) || !rows.length || rows.length > 180) throw accessError(400, "Provide bounded ordered results");
    results = rows.map(row => {
      if (!row || typeof row.testCode !== "string" || row.testCode.length > 80 || typeof row.parameterCode !== "string" || row.parameterCode.length > 80
        || !["number", "string"].includes(typeof row.value) || (typeof row.value === "number" && !Number.isFinite(row.value))
        || (typeof row.value === "string" && row.value.length > 2000)) throw accessError(400, "Invalid result input");
      return { testCode: row.testCode, parameterCode: row.parameterCode, value: row.value };
    }).sort((a, b) => JSON.stringify([a.testCode, a.parameterCode]).localeCompare(JSON.stringify([b.testCode, b.parameterCode])));
  }
  const reason = ["reject", "correct"].includes(kind) ? clinicalText(input.reason, "Reason", 1000) : "";
  if (["reject", "correct"].includes(kind) && !reason) throw accessError(400, "A reason is required");
  if (kind === "collect" && input.customBarcode) throw accessError(400, "Accession identifiers are generated by the server");
  if (kind === "reject" && input.requestRecollection !== undefined && typeof input.requestRecollection !== "boolean") throw accessError(400, "Recollection must be true or false");
  if (kind === "acknowledge" && (!Number.isSafeInteger(input.reportVersion) || input.reportVersion < 1)) throw accessError(400, "The critical report version is required");
  const data = { kind, actor: requireRecordId(input.actor?.id, "staff"), revision: input.expectedRevision, results, reason,
    recollect: kind === "reject" ? input.requestRecollection !== false : undefined, reportVersion: kind === "acknowledge" ? input.reportVersion : undefined };
  return { ...data, key: input.requestKey, hash: fingerprint(data) };
}
const roles = { billing: ["RECEPTIONIST", "HOSPITAL_ADMIN"], collect: ["NURSE", "LAB_TECH"], reject: ["LAB_TECH"],
  results: ["LAB_TECH"], verify: ["DOCTOR", "LAB_TECH"], release: ["DOCTOR", "LAB_TECH"], correct: ["LAB_TECH", "DOCTOR"], acknowledge: ["DOCTOR"] };
const audit = (order, actor, stage, notes) => order.auditHistory.push({ stage, actorId: actor._id, actorName: actor.name, timestamp: new Date(), notes });
function appendReport(order, actor, cmd) {
  if (order.reportVersions.length >= 30) throw accessError(409, "Report version limit requires reviewed follow-up");
  const results = resolveLabResults(order.tests, cmd.results), now = new Date();
  const version = (order.reportVersions.at(-1)?.version || 0) + 1;
  order.reportVersions.push({ version, results, authorId: actor._id, authorName: actor.name, enteredAt: now, correctionReason: cmd.reason || undefined });
  order.reportVersion = version; order.results = results;
  order.orderStatus = "result_entered"; order.technicianId = actor._id; order.technicianName = actor.name; order.resultEnteredAt = now;
  order.verifiedAt = undefined; order.verifiedById = undefined; order.verifiedByName = undefined;
  // Earlier release provenance lives on its immutable version and remains patient-visible.
  order.criticalValueAlert = { isCritical: results.some(r => r.isCritical) };
}

export async function labCommand(input, kind) {
  if (!Object.hasOwn(roles, kind)) throw accessError(400, "Unknown laboratory action");
  // Resolve role/scope before reporting a missing command contract, as on the pharmacy route.
  if (mongoose.connection.readyState !== 1) throw accessError(503, "Database service is unavailable");
  return transaction(async session => {
    const order = await loadClinicalRecord(LabOrder, input.orderId, input.hospitalId, input.actor, "lab", roles[kind], { session, billing: kind === "billing" });
    const actor = await clinicalStaff(input.actor, input.hospitalId, { session });
    if (["verify", "release"].includes(kind) && !canReviewLab(actor, order)) throw accessError(403, "Explicit hospital approval for this laboratory department is required");
    const cmd = command(input, kind), prior = order.workflowCommands.find(op => op.key === cmd.key);
    if (prior) {
      if (prior.hash !== cmd.hash) throw accessError(409, "This command key was already used with different contents");
      order.$locals.replayed = true; return order;
    }
    if (order.workflowVersion !== 1) throw accessError(409, "Historical laboratory workflow needs reviewed provenance repair");
    if (order.workflowRevision !== cmd.revision) throw accessError(409, "Laboratory order changed; refresh before retrying");
    if (order.workflowCommands.length >= 256) throw accessError(409, "Laboratory command limit requires reviewed follow-up");
    const now = new Date(), report = order.reportVersions.at(-1);
    if (kind === "billing") {
      if (order.orderStatus !== "ordered") throw accessError(409, "Billing clearance requires an ordered test");
      order.orderStatus = "billing_cleared";
    } else if (kind === "collect") {
      if (!["ordered", "billing_cleared", "rejected"].includes(order.orderStatus) || (order.orderStatus === "rejected" && !order.recollectionRequested)) throw accessError(409, "This specimen cannot be collected");
      order.sampleSequence += 1;
      order.accessionBarcode = generateAccessionBarcode(order._id, order.sampleSequence);
      order.samples.push({ barcode: order.accessionBarcode, collectedAt: now, collectedBy: actor._id });
      order.collectedAt = now; order.collectedBy = actor._id; order.collectedByName = actor.name;
      order.orderStatus = "collected"; order.recollectionRequested = false; order.rejectedReason = undefined;
    } else if (kind === "reject") {
      if (!order.samples.length || !["collected", "processing", "result_entered"].includes(order.orderStatus)) throw accessError(409, "Only an unverified collected specimen can be rejected");
      Object.assign(order.samples.at(-1), { rejectedAt: now, rejectedBy: actor._id, rejectionReason: cmd.reason });
      order.orderStatus = "rejected"; order.rejectedReason = cmd.reason; order.recollectionRequested = cmd.recollect;
      order.results = []; order.criticalValueAlert = { isCritical: false };
    } else if (kind === "results") {
      if (!["collected", "processing", "result_entered"].includes(order.orderStatus)) throw accessError(409, "Results require an unverified collected specimen");
      appendReport(order, actor, cmd);
    } else if (kind === "correct") {
      if (!["verified", "released"].includes(order.orderStatus) || !report?.verifiedAt) throw accessError(409, "Correction requires a reviewed report");
      appendReport(order, actor, cmd);
    } else if (kind === "verify") {
      if (order.orderStatus !== "result_entered" || !report || report.verifiedAt || report.version !== order.reportVersion) throw accessError(409, "Only the current unverified draft can be reviewed");
      if (idOf(report.authorId) === idOf(actor._id)) throw accessError(403, "A different approved person must review this report");
      Object.assign(report, { verifiedById: actor._id, verifiedByName: actor.name, verifiedAt: now });
      order.verifiedById = actor._id; order.verifiedByName = actor.name; order.verifiedAt = now; order.orderStatus = "verified";
      if (report.results.some(result => result.isCritical)) report.criticalTask = { assignedDoctorId: order.orderingDoctorId, createdAt: now };
    } else if (kind === "release") {
      if (order.orderStatus !== "verified" || !report?.verifiedAt || report.releasedAt || report.version !== order.reportVersion) throw accessError(409, "Release requires the current verified report");
      Object.assign(report, { releasedById: actor._id, releasedByName: actor.name, releasedAt: now });
      order.orderStatus = "released"; order.releasedAt = now; order.releasedBy = actor._id;
    } else if (kind === "acknowledge") {
      const target = order.reportVersions.find(r => r.version === cmd.reportVersion);
      if (idOf(order.orderingDoctorId) !== idOf(actor._id) || idOf(target?.criticalTask?.assignedDoctorId) !== idOf(actor._id)) throw accessError(403, "Only the assigned clinician may acknowledge this version's task");
      if (!target.criticalTask.createdAt || target.criticalTask.acknowledgedAt) throw accessError(409, "This critical task is not pending");
      Object.assign(target.criticalTask, { acknowledgedAt: now, acknowledgedById: actor._id, acknowledgedByName: actor.name });
      if (target.version === order.reportVersion) { order.criticalValueAlert.acknowledgedAt = now; order.criticalValueAlert.acknowledgedBy = actor.name; }
    }
    audit(order, actor, kind, cmd.reason || `Laboratory ${kind}; report version ${order.reportVersion}`);
    order.workflowRevision += 1;
    order.workflowCommands.push({ key: cmd.key, hash: cmd.hash, kind, actorId: actor._id, timestamp: now, resultingRevision: order.workflowRevision });
    if (Buffer.byteLength(JSON.stringify(order.toObject()), "utf8") > 8 * 1024 * 1024) throw accessError(409, "Laboratory history size requires reviewed follow-up before further changes");
    // Serialize capability revocation/role changes with publication, not just with order writes.
    if (process.env.NODE_ENV === "test" && fault) await fault("beforeAuthorizationFence");
    await HospitalStaff.updateOne({ _id: actor._id }, { $inc: { clinicalAuthorizationRevision: 1 } }, { session });
    if (process.env.NODE_ENV === "test" && fault) await fault("beforeOrderSave");
    await order.save({ session });
    return order;
  });
}

export async function approveLabReviewer({ hospitalId, actor, staffId, enabled, departmentIds, qualificationReference }) {
  requireRecordId(staffId, "reviewer");
  if (typeof enabled !== "boolean") throw accessError(400, "Approval enabled must be true or false");
  const reference = clinicalText(qualificationReference, "Qualification review reference", 500);
  if (enabled && (!reference || !Array.isArray(departmentIds) || !departmentIds.length || departmentIds.length > 30)) throw accessError(400, "Reviewed qualification reference and assigned departments are required");
  return transaction(async session => {
    const approver = await clinicalStaff(actor, hospitalId, { session });
    if (approver.role !== "HOSPITAL_ADMIN" && !approver.adminAccess) throw accessError(403, "Hospital administration is required to record approval");
    if (idOf(approver._id) === idOf(staffId)) throw accessError(403, "Staff cannot approve their own clinical capability");
    const target = await HospitalStaff.findOne({ _id: staffId, hospitalId, isActive: true, inviteStatus: "accepted", role: { $in: ["DOCTOR", "LAB_TECH"] } }).session(session);
    if (!target) throw accessError(403, "Choose an active accepted doctor or laboratory staff member");
    const departments = enabled ? [...new Set(departmentIds.map(value => requireRecordId(value, "department")))] : [];
    for (const dept of departments) if (!target.departmentIds.some(d => idOf(d) === dept) || !await Department.exists({ _id: dept, hospitalId, status: "active" }).session(session)) throw accessError(403, "Review approval must match active assigned departments");
    if (target.labReviewApprovalHistory.length >= 128) throw accessError(409, "Approval history limit requires reviewed follow-up");
    const approval = { enabled, departmentIds: departments, qualificationReference: reference, approvedBy: approver._id, approvedAt: new Date() };
    target.labReviewApproval = approval; target.labReviewApprovalHistory.push(approval);
    await HospitalStaff.updateOne({ _id: approver._id }, { $inc: { clinicalAuthorizationRevision: 1 } }, { session });
    await target.save({ session });
    return { staffId: idOf(target._id), enabled, departmentIds: labReviewDepartments(target) };
  });
}
